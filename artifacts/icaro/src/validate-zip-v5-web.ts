import assert from "node:assert/strict";
import { escapeIcsText, parseAgendaEntries, serializeCalendar, toIcsLocalDate, type AgendaEntry } from "./lib/agenda-format";
import { parseSpotifyLink, spotifyEmbedUrl } from "./lib/spotify-links";
import { DEMO_TOURS, parseOpenTour, parseTourCommand, tourById, tourStep } from "./lib/demo-tours";
import { interpret, normalize } from "./lib/commands";
import { geocodeUrl, googleMapEmbedUrl, googleMapsLink, isValidGeoTarget, parseFlyQuery, parseGeocode, type GeoTarget } from "./lib/geo-fly";

let checks = 0;
function check(value: unknown, message: string) {
  checks += 1;
  assert.ok(value, `Validação web ${checks}: ${message}`);
}

const single: AgendaEntry = { id: "abc", title: "Reunião", startsAt: "2026-10-12T09:30", recurrence: "none" };
check(parseAgendaEntries([single]).length === 1, "aceita compromisso válido");
check(parseAgendaEntries([{ ...single, recurrence: "daily" }])[0]?.recurrence === "daily", "aceita rotina diária");
check(parseAgendaEntries([{ ...single, recurrence: "weekly" }])[0]?.recurrence === "weekly", "aceita rotina semanal");
check(parseAgendaEntries(null).length === 0, "rejeita armazenamento nulo");
check(parseAgendaEntries({ entries: [single] }).length === 0, "rejeita formato objeto inesperado");
check(parseAgendaEntries([null]).length === 0, "rejeita item nulo");
check(parseAgendaEntries([{ ...single, id: "" }]).length === 0, "rejeita identificador vazio");
check(parseAgendaEntries([{ ...single, title: "" }]).length === 0, "rejeita título vazio");
check(parseAgendaEntries([{ ...single, title: "  " }]).length === 0, "rejeita título só com espaços");
check(parseAgendaEntries([{ ...single, startsAt: "inválido" }]).length === 0, "rejeita data inválida");
check(parseAgendaEntries([{ ...single, recurrence: "monthly" }]).length === 0, "rejeita recorrência desconhecida");
check(parseAgendaEntries([single, { ...single, id: "bad", startsAt: "bad" }]).length === 1, "filtra dados inválidos sem descartar os válidos");
check(escapeIcsText("a,b") === "a\\,b", "escapa vírgula no ICS");
check(escapeIcsText("a;b") === "a\\;b", "escapa ponto e vírgula no ICS");
check(escapeIcsText("a\\b") === "a\\\\b", "escapa barra invertida no ICS");
check(escapeIcsText("a\nb") === "a\\nb", "escapa quebra de linha no ICS");
check(escapeIcsText("Reunião") === "Reunião", "preserva caracteres Unicode");
check(toIcsLocalDate("invalid") === "", "não serializa data inválida");
check(/^\d{8}T\d{6}$/.test(toIcsLocalDate("2026-10-12T09:30")), "formata data local ICS");
const empty = serializeCalendar([], new Date("2026-01-01T00:00:00Z"), "America/Sao_Paulo");
check(empty.startsWith("BEGIN:VCALENDAR\r\n"), "inicia envelope de calendário");
check(empty.includes("VERSION:2.0\r\n"), "inclui versão do padrão");
check(empty.includes("PRODID:-//ICARO//Agenda//PT-BR\r\n"), "identifica o calendário Ícaro");
check(empty.endsWith("END:VCALENDAR\r\n"), "fecha envelope com CRLF");
const once = serializeCalendar([single], new Date("2026-01-01T00:00:00Z"), "America/Sao_Paulo");
check((once.match(/BEGIN:VEVENT/g) ?? []).length === 1, "exporta um compromisso como evento");
check(once.includes("UID:abc@icaro.local"), "exporta UID estável do evento");
check(once.includes("DTSTART;TZID=America/Sao_Paulo:"), "exporta horário local com fuso");
check(once.includes("SUMMARY:Reunião\r\n"), "exporta o título do compromisso");
check(!once.includes("RRULE:"), "não adiciona recorrência a compromisso único");
check(serializeCalendar([{ ...single, recurrence: "daily" }]).includes("RRULE:FREQ=DAILY"), "exporta repetição diária");
check(serializeCalendar([{ ...single, recurrence: "weekly" }]).includes("RRULE:FREQ=WEEKLY"), "exporta repetição semanal");
check(serializeCalendar([{ ...single, title: "A,B;C" }]).includes("SUMMARY:A\\,B\\;C"), "escapa pontuação no título exportado");
check((serializeCalendar([single, { ...single, id: "def" }]).match(/BEGIN:VEVENT/g) ?? []).length === 2, "exporta múltiplos compromissos");

const track = "https://open.spotify.com/track/4uLU6hMCjMI75M1A2tKUQC";
const playlist = "https://open.spotify.com/playlist/37i9dQZF1DXcBWIGoYBM5M";
check(parseSpotifyLink(track)?.id === "4uLU6hMCjMI75M1A2tKUQC", "aceita URL canônica de faixa");
check(parseSpotifyLink(`${track}?si=demo`)?.id === "4uLU6hMCjMI75M1A2tKUQC", "ignora parâmetros de compartilhamento");
check(parseSpotifyLink("https://open.spotify.com/intl-pt/album/4aawyAB9vmqN3uQ7FjRGTy")?.id === "4aawyAB9vmqN3uQ7FjRGTy", "aceita URL localizada de álbum");
check(parseSpotifyLink(playlist)?.id === "37i9dQZF1DXcBWIGoYBM5M", "aceita URL de playlist");
check(parseSpotifyLink("http://open.spotify.com/track/4uLU6hMCjMI75M1A2tKUQC") === null, "rejeita HTTP sem TLS");
check(parseSpotifyLink("https://evil.example/track/4uLU6hMCjMI75M1A2tKUQC") === null, "rejeita host não confiável");
check(parseSpotifyLink("https://open.spotify.com/artist/4uLU6hMCjMI75M1A2tKUQC") === null, "rejeita tipo não incorporável");
check(parseSpotifyLink("https://open.spotify.com/track/short") === null, "rejeita identificador malformado");
check(parseSpotifyLink("texto livre") === null, "rejeita link inválido");
check(spotifyEmbedUrl({ id: "4uLU6hMCjMI75M1A2tKUQC", title: "Demo", url: track }) === "https://open.spotify.com/embed/track/4uLU6hMCjMI75M1A2tKUQC", "constrói player seguro para faixa");
check(spotifyEmbedUrl({ id: "x", title: "Demo", url: "https://evil.example/track/x" }) === "", "não incorpora host externo");

check(DEMO_TOURS.length === 2, "oferece os dois sistemas do professor");
check(tourById("discipulus")?.steps.length === 6, "tour do Discipulus com seis etapas");
check(tourById("labeducontabil")?.steps.length === 5, "tour do LabEduContábil com cinco etapas");
check(tourById("inexistente") === null, "rejeita sistema desconhecido");
check(tourStep(DEMO_TOURS[0], 0)?.title === "O que é", "tour inicia pela apresentação");
check(tourStep(DEMO_TOURS[0], 99) === null, "rejeita etapa fora do intervalo");
check(parseOpenTour(normalize("Ícaro, mostre o Discipulus")) === "discipulus", "voz abre o Discipulus");
check(parseOpenTour(normalize("mostre o LabEduContábil")) === "labeducontabil", "voz abre o LabEduContábil");
check(parseOpenTour(normalize("mostre a galáxia")) === null, "não confunde galáxia com sistema");
check(parseTourCommand(normalize("próximo")) === "next", "voz avança o tour");
check(parseTourCommand(normalize("volte")) === "previous", "voz volta o tour");
check(parseTourCommand(normalize("pausa")) === "pause", "voz pausa o tour");
check(parseTourCommand(normalize("continue")) === "resume", "voz retoma o tour");
check(parseTourCommand(normalize("feche o sistema")) === "close", "voz fecha o tour");
check(parseTourCommand(normalize("que horas são")) === null, "pergunta comum não vira comando de tour");
const openTourCmd = interpret("Ícaro, mostre o Discipulus");
check(openTourCmd.kind === "openTour" && openTourCmd.tour === "discipulus", "interpret abre o Discipulus");
check(interpret("Ícaro, mostre o LabEduContábil").kind === "openTour", "interpret abre o LabEduContábil");
check(interpret("próximo").kind === "tour", "interpret controla o tour");
const playCmd = interpret("toque música");
check(playCmd.kind === "openMusic" && playCmd.play, "interpret toca música");
const openCmd = interpret("abra o spotify");
check(openCmd.kind === "openMusic" && !openCmd.play, "interpret só abre o Spotify sem tocar");
check(interpret("mostre a galáxia").kind === "scene", "cena da galáxia preservada");
check(interpret("que horas são").kind === "say", "pergunta de hora preservada");

check(parseFlyQuery(normalize("onde fica Tóquio")) === "toquio", "extrai pergunta onde fica");
check(parseFlyQuery(normalize("me mostre Salvador no mapa")) === "salvador", "extrai pedido de mapa");
check(parseFlyQuery(normalize("voe para Lisboa")) === "lisboa", "extrai comando de voo");
check(parseFlyQuery(normalize("navegue até Nova York, Estados Unidos")) === "nova york, estados unidos", "mantém nomes compostos e país");
check(parseFlyQuery(normalize("localize a Rua Augusta")) === "rua augusta", "aceita comando de localizar endereço");
check(parseFlyQuery(normalize("abra o Google Maps de Paris")) === "paris", "aceita comando direto de abrir Maps");
check(parseFlyQuery(normalize("que horas são")) === null, "pergunta de hora não vira voo");
check(parseFlyQuery(normalize("toque música")) === null, "comando de música não vira voo");
check(parseFlyQuery(normalize("")) === null, "entrada vazia não vira destino");
check(geocodeUrl("São Paulo").startsWith("https://photon.komoot.io/api/"), "usa geocodificador Photon HTTPS");
check(geocodeUrl("São Paulo").includes("q=S%C3%A3o%20Paulo"), "codifica acentos na busca");
check(geocodeUrl("Rua A").includes("limit=1"), "limita resultado de busca");
check(!geocodeUrl("Rua A").includes("lang=pt"), "não envia idioma não suportado pelo Photon");
const photon = { features: [{ geometry: { coordinates: [-46.65, -23.56] }, properties: { name: "Avenida Paulista", housenumber: "1000", street: "Avenida Paulista", city: "São Paulo", state: "São Paulo", country: "Brasil" } }] };
const paulista = parseGeocode(photon);
check(paulista !== null, "aceita resultado Photon");
check(paulista?.latitude === -23.56 && paulista.longitude === -46.65, "converte ordem GeoJSON lon/lat corretamente");
check(paulista?.street === "1000 Avenida Paulista", "preserva número e nome da rua");
check(paulista?.city === "São Paulo", "extrai cidade");
check(paulista?.state === "São Paulo", "extrai estado");
check(paulista?.country === "Brasil", "extrai país");
check(paulista?.label === "1000 Avenida Paulista, São Paulo, Brasil", "monta endereço hierárquico legível");
check(parseGeocode({ features: [] }) === null, "trata busca sem resultados");
check(parseGeocode(null) === null, "trata resposta nula");
check(parseGeocode({ features: [{ geometry: { coordinates: ["x", 1] }, properties: {} }] }) === null, "rejeita coordenadas não numéricas");
check(parseGeocode({ features: [{ geometry: { coordinates: [181, 0] }, properties: {} }] }) === null, "rejeita longitude fora da Terra");
check(parseGeocode({ features: [{ geometry: { coordinates: [0, 91] }, properties: {} }] }) === null, "rejeita latitude fora da Terra");
const target: GeoTarget = { latitude: -23.56, longitude: -46.65, label: "São Paulo" };
check(isValidGeoTarget(target), "valida coordenadas terrestres");
check(!isValidGeoTarget({ ...target, latitude: 91 }), "validador rejeita latitude impossível");
check(!isValidGeoTarget({ ...target, longitude: 181 }), "validador rejeita longitude impossível");
check(googleMapEmbedUrl(target, "map").startsWith("https://www.google.com/maps?"), "mapa usa domínio oficial Google");
check(googleMapEmbedUrl(target, "map").includes("q=-23.56,-46.65"), "mapa centraliza nas coordenadas exatas");
check(googleMapEmbedUrl(target, "map").includes("t=m&output=embed"), "gera mapa de ruas incorporado");
check(googleMapEmbedUrl(target, "satellite").includes("t=k&output=embed"), "gera camada de satélite");
check(googleMapEmbedUrl(target, "street") === "", "não tenta incorporar Street View sem API key");
check(googleMapsLink(target, "street").includes("map_action=pano&viewpoint=-23.56,-46.65"), "Street View abre panorama nas coordenadas exatas");
check(googleMapsLink(target, "street").startsWith("https://www.google.com/maps/@?api=1"), "Street View usa deep-link oficial do Google");
check(googleMapEmbedUrl(target, "map", 99).includes("&z=20&"), "limita zoom máximo");
check(googleMapEmbedUrl(target, "map", 0).includes("&z=2&"), "limita zoom mínimo");
check(googleMapsLink(target, "street").includes("map_action=pano&viewpoint=-23.56,-46.65"), "link externo abre panorama no ponto exato");
check(googleMapsLink(target, "map").includes("query=-23.56,-46.65"), "link externo abre busca do Maps");
check(googleMapEmbedUrl({ ...target, latitude: 91 }, "map") === "", "não incorpora coordenadas inválidas");
check(interpret("onde fica Tóquio").kind === "flyTo", "voz inicia busca geográfica");
check(interpret("vá para Lisboa").kind === "flyTo", "voz navega para destino");
check(interpret("voe para Feira de Santana").kind === "flyFeira", "mantém rota especial de Feira");
check(interpret("Ícaro, onde fica o Vaticano").kind === "flyTo", "aceita palavra de ativação");

assert.equal(checks, 109);
process.stdout.write(`ÍCARO v5 web: ${checks}/${checks} validações de agenda, Spotify, tours, voz, geocodificação e Google Maps passaram.\n`);
